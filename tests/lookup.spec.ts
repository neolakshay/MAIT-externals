test('switching semesters clears the group and shared links include the correct semester', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('./?group=C1')
  await page.waitForLoadState('networkidle')
  await expect(page.locator('.exam-card').first()).toContainText('Engineering Physics Lab')
  await page.getByRole('radio', { name: 'Sem 3', exact: true }).check()
  const search = page.getByRole('combobox')
  await expect(search).toHaveValue('')
  await expect(page.locator('.exam-card')).toHaveCount(0)
  await search.fill('C-1')
  await search.press('Enter')
  await expect(search).toHaveValue('C1')
  await expect(page.locator('.exam-card')).toHaveCount(4)
  await expect(page.locator('.exam-card').first()).toContainText('Computational Methods Lab')
  await expect(page.getByRole('link', { name: 'View semester 3 datesheet' })).toHaveAttribute('href', /\.pdf#page=1$/)
  await page.getByRole('radio', { name: 'Sem 5', exact: true }).check()
  await expect(search).toHaveValue('')
  await search.fill('C1')
  await search.press('Enter')
  await expect(page.locator('.exam-card')).toHaveCount(5)
  await expect(page.locator('.exam-card').first()).toContainText('Compiler Design Lab')
  await expect(page.getByRole('link', { name: 'View semester 5 datesheet' })).toHaveAttribute('href', /\.pdf#page=2$/)
  await page.getByRole('button', { name: 'Copy link' }).click()
  const sharedUrl = await page.evaluate(() => navigator.clipboard.readText())
  expect(new URL(sharedUrl).searchParams.get('semester')).toBe('5')
  expect(new URL(sharedUrl).searchParams.get('group')).toBe('C1')
  await page.getByRole('radio', { name: 'Sem 3', exact: true }).check()
  await expect(search).toHaveValue('')
  await expect(page.locator('.exam-card')).toHaveCount(0)
  expect(new URL(page.url()).searchParams.has('group')).toBe(false)
  await page.goBack()
  await expect(page.getByRole('radio', { name: 'Sem 5', exact: true })).toBeChecked()
  await page.goto('./')
  await expect(page.getByRole('radio', { name: 'Sem 5', exact: true })).toBeChecked()
  await expect(search).toHaveValue('')
  await page.goto(sharedUrl)
  await expect(search).toHaveValue('C1')
  await page.reload()
  await expect(page.getByRole('radio', { name: 'Sem 5', exact: true })).toBeChecked()
  await expect(search).toHaveValue('')
  await expect(page.locator('.exam-card')).toHaveCount(0)
  // Legacy group links continue to refer to semester 1, even after saving semester 5.
  await page.goto('./?group=C1')
  await expect(page.getByRole('radio', { name: 'Sem 1', exact: true })).toBeChecked()
  await expect(page.locator('.exam-card').first()).toContainText('Engineering Physics Lab')
})

